/**
 * Get a display label for a part status.
 *
 * @since 0.8.0
 * @param string $status Part status.
 * @return string
 */
function variable_thema_get_part_status_label( $status ) {
	$labels = array(
		'implemented' => __( 'Implemented', 'variable-thema' ),
		'planned'     => __( 'Planned', 'variable-thema' ),
		'optional'    => __( 'Optional', 'variable-thema' ),
		'gateway'     => __( 'Integration point only', 'variable-thema' ),
		'deprecated'  => __( 'Deprecated / Saving disabled', 'variable-thema' ),
	);

	return isset( $labels[ $status ] ) ? $labels[ $status ] : $status;
}
